"""HTTP API with the fake Claude client."""

import base64
from collections.abc import Iterator
from pathlib import Path

import pytest
from fastapi.testclient import TestClient
from pydantic import SecretStr
from sqlalchemy import Engine

from app.api.ask import get_today
from app.assistant.llm_client import LlmError
from app.config import get_settings
from app.main import create_app
from tests.conftest import TODAY
from tests.fakes import Step, factory, reply, tool_use

SCRIPT: list[Step] = [
    reply(tool_use("stock_bas", {}, "c1")),
    reply(tool_use("repondre", {"texte": "Rachète le thé.", "langue": "fr"}, "c2")),
]


@pytest.fixture(autouse=True)
def no_side_effects(monkeypatch: pytest.MonkeyPatch) -> None:
    # The seeded test shop must not move or be regenerated by the app's startup.
    settings = get_settings()
    monkeypatch.setattr(settings, "slide_dates_on_startup", False)
    monkeypatch.setattr(settings, "app_password", None)


def make_client(engine: Engine, tmp_path: Path, script: list[Step]) -> TestClient:
    app = create_app(engine=engine, llm_client_factory=factory(script), static_dir=tmp_path)
    app.dependency_overrides[get_today] = lambda: TODAY
    return TestClient(app)


@pytest.fixture
def client(shop_db: Engine, tmp_path: Path) -> Iterator[TestClient]:
    with make_client(shop_db, tmp_path, list(SCRIPT)) as client:
        yield client


def test_ask(client: TestClient) -> None:
    body = client.post("/api/ask", json={"question": "Je rachète quoi ?", "history": []}).json()
    assert body["answer"] == "Rachète le thé." and body["language"] == "fr"
    assert body["cards"][0]["tool"] == "stock_bas" and body["cards"][0]["title"]
    assert body["llm_calls"] == 2 and body["cost_usd"] > 0


def test_ask_validates_input(client: TestClient) -> None:
    assert client.post("/api/ask", json={"question": ""}).status_code == 422


def test_llm_error_is_a_502(shop_db: Engine, tmp_path: Path) -> None:
    with make_client(shop_db, tmp_path, [LlmError("service indisponible")]) as client:
        response = client.post("/api/ask", json={"question": "Bonjour"})
    assert response.status_code == 502 and response.json()["detail"] == "service indisponible"


def test_shop_summary(client: TestClient) -> None:
    shop = client.get("/api/shop").json()
    assert shop["fictional"] is True and shop["last_day"] == TODAY.isoformat()
    assert shop["products"] > 0 and shop["receipts"] > 0


def test_password_protects_everything_but_health_and_manifest(
    shop_db: Engine, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(get_settings(), "app_password", SecretStr("secret"))
    (tmp_path / "index.html").write_text("<app-root></app-root>", encoding="utf-8")
    (tmp_path / "manifest.webmanifest").write_text("{}", encoding="utf-8")
    with make_client(shop_db, tmp_path, []) as client:
        assert client.get("/api/shop").status_code == 401
        assert client.get("/health").status_code == 200
        assert client.get("/manifest.webmanifest").status_code == 200
        token = base64.b64encode(b"boutique:secret").decode()
        auth = {"Authorization": f"Basic {token}"}
        assert client.get("/api/shop", headers=auth).status_code == 200
